#!/usr/bin/env python3
"""Generate site and app GitHub settings from Config/github-config.json.

Usage:
  python3 scripts/generate-site-config.py [--check]

Updates the config block in site/app.js and the GitHub keys in
Config/Defaults.plist. --check verifies both files without writing them.
"""

import json
import plistlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG_PATH = ROOT / "Config" / "github-config.json"
APP_JS_PATH = ROOT / "site" / "app.js"
DEFAULTS_PATH = ROOT / "Config" / "Defaults.plist"
BEGIN = "  // BEGIN CONFIG (generated by scripts/generate-site-config.py)"
END = "  // END CONFIG"


def load_config() -> dict:
    with CONFIG_PATH.open() as f:
        return json.load(f)


def render_block(config: dict) -> str:
    hosts = ", ".join(json.dumps(h) for h in config["allowed_download_hosts"])
    return (
        BEGIN + "\n"
        + f"  var fallbackDownloadURL =\n    {json.dumps(config['fallback_download_url'])};\n"
        + f"  var expectedRepository = {json.dumps(config['expected_repository'])};\n"
        + f"  var allowedDownloadHosts = [{hosts}];\n"
        + f"  var githubAPIBase = {json.dumps(config['github_api_base'])};\n"
        + END
    )


def apply(content: str, block: str) -> str:
    if content.count(BEGIN) != 1 or content.count(END) != 1:
        raise ValueError("config markers must occur exactly once")
    start = content.index(BEGIN)
    end = content.index(END)
    if end < start:
        raise ValueError("config markers are not in order")
    return content[:start] + block + content[end + len(END):]


def render_defaults(content: bytes, config: dict) -> bytes:
    defaults = plistlib.loads(content)
    defaults.update({
        "ExpectedGitHubRepository": config["expected_repository"],
        "GitHubReleasesAPIURL": config["github_api_base"] + "/releases/latest",
        "UpdateDownloadFallbackURL": config["fallback_download_url"],
        "AllowedUpdateDownloadHosts": config["allowed_download_hosts"],
    })
    return plistlib.dumps(defaults, sort_keys=False)


def main() -> int:
    config = load_config()
    content = APP_JS_PATH.read_text(encoding="utf-8")
    try:
        updated = apply(content, render_block(config))
    except ValueError as error:
        sys.stderr.write(f"{APP_JS_PATH}: {error}\n")
        return 1

    # Prepare both outputs before writing either file.
    defaults = DEFAULTS_PATH.read_bytes()
    updated_defaults = render_defaults(defaults, config)
    outputs = [
        (APP_JS_PATH, content.encode("utf-8"), updated.encode("utf-8")),
        (DEFAULTS_PATH, defaults, updated_defaults),
    ]
    stale = [(path, new) for path, old, new in outputs if old != new]
    if "--check" in sys.argv:
        for path, _ in stale:
            sys.stderr.write(
                f"{path} is out of date. Run python3 scripts/generate-site-config.py.\n"
            )
        return 1 if stale else 0

    for path, new in stale:
        path.write_bytes(new)
        print(f"Updated {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
