#!/usr/bin/env python3
"""GitHub 設定生成の CLI 回帰テスト（標準ライブラリのみ）。"""

import json
import plistlib
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "  // BEGIN CONFIG (generated by scripts/generate-site-config.py)"
END = "  // END CONFIG"


class GenerateSiteConfigTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        for name in ("scripts/generate-site-config.py", "Config/github-config.json",
                     "Config/Defaults.plist", "site/app.js"):
            target = self.root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(ROOT / name, target)
        self.app = self.root / "site/app.js"
        self.defaults = self.root / "Config/Defaults.plist"
        self.config_path = self.root / "Config/github-config.json"
        self.config = json.loads(self.config_path.read_text(encoding="utf-8"))

    def run_generator(self, *args):
        # cwd に依存せず、スクリプトの配置先を基準にファイルを扱う。
        return subprocess.run(
            [sys.executable, str(self.root / "scripts/generate-site-config.py"), *args],
            cwd=self.root / "site", capture_output=True, text=True, check=False,
        )

    def snapshot(self):
        return self.app.read_bytes(), self.defaults.read_bytes()

    def assert_success(self, result):
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_current_outputs_and_generation_are_idempotent(self):
        before = self.snapshot()
        self.assert_success(self.run_generator("--check"))
        self.assertEqual(self.snapshot(), before)
        self.assert_success(self.run_generator())
        self.assertEqual(self.snapshot(), before)
        self.assert_success(self.run_generator())
        self.assertEqual(self.snapshot(), before)

    def test_changed_config_updates_both_outputs_only_in_owned_settings(self):
        self.config.update({
            "expected_repository": "Example/OtherApp",
            "github_api_base": "https://api.github.com/repos/Example/OtherApp",
            "fallback_download_url": "https://downloads.example.com/Other.dmg",
            "allowed_download_hosts": ["downloads.example.com", "github.com"],
        })
        self.config_path.write_text(json.dumps(self.config), encoding="utf-8")
        before_app = self.app.read_text(encoding="utf-8")
        before_defaults = plistlib.loads(self.defaults.read_bytes())
        result = self.run_generator("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn(str(self.app), result.stderr)
        self.assertIn(str(self.defaults), result.stderr)
        self.assertEqual(self.app.read_text(encoding="utf-8"), before_app)
        self.assertEqual(plistlib.loads(self.defaults.read_bytes()), before_defaults)

        self.assert_success(self.run_generator())
        generated = self.app.read_text(encoding="utf-8")
        self.assertEqual(generated.split(BEGIN)[0], before_app.split(BEGIN)[0])
        self.assertEqual(generated.split(END)[1], before_app.split(END)[1])
        block = generated.split(BEGIN)[1].split(END)[0]
        for variable, key in (
            ("expectedRepository", "expected_repository"),
            ("githubAPIBase", "github_api_base"),
            ("fallbackDownloadURL", "fallback_download_url"),
            ("allowedDownloadHosts", "allowed_download_hosts"),
        ):
            self.assertIn(f"var {variable} =", block)
            self.assertIn(json.dumps(self.config[key]), block)
        expected_defaults = dict(before_defaults)
        expected_defaults.update({
            "ExpectedGitHubRepository": self.config["expected_repository"],
            "GitHubReleasesAPIURL": self.config["github_api_base"] + "/releases/latest",
            "UpdateDownloadFallbackURL": self.config["fallback_download_url"],
            "AllowedUpdateDownloadHosts": self.config["allowed_download_hosts"],
        })
        self.assertEqual(plistlib.loads(self.defaults.read_bytes()), expected_defaults)
        generated_files = self.snapshot()
        self.assert_success(self.run_generator("--check"))
        self.assert_success(self.run_generator())
        self.assertEqual(self.snapshot(), generated_files)

    def test_check_detects_each_stale_plist_key_without_writing(self):
        original = self.defaults.read_bytes()
        for key, value in (
            ("ExpectedGitHubRepository", "stale/repo"),
            ("GitHubReleasesAPIURL", "https://api.example.com/stale"),
            ("UpdateDownloadFallbackURL", "https://example.com/stale.dmg"),
            ("AllowedUpdateDownloadHosts", ["stale.example.com"]),
        ):
            with self.subTest(key=key):
                defaults = plistlib.loads(original)
                defaults[key] = value
                self.defaults.write_bytes(plistlib.dumps(defaults, sort_keys=False))
                before = self.snapshot()
                result = self.run_generator("--check")
                self.assertEqual(result.returncode, 1)
                self.assertIn(str(self.defaults), result.stderr)
                self.assertNotIn(f"{self.app} is out of date", result.stderr)
                self.assertEqual(self.snapshot(), before)
                self.assert_success(self.run_generator())
                self.assertEqual(self.defaults.read_bytes(), original)

    def test_check_detects_stale_js_without_writing(self):
        valid = f"var expectedRepository = {json.dumps(self.config['expected_repository'])};"
        original = self.app.read_text(encoding="utf-8")
        self.assertIn(valid, original)
        self.app.write_text(original.replace(
            valid, 'var expectedRepository = "stale/repo";'), encoding="utf-8")
        before = self.snapshot()
        result = self.run_generator("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn(str(self.app), result.stderr)
        self.assertNotIn(f"{self.defaults} is out of date", result.stderr)
        self.assertEqual(self.snapshot(), before)
        self.assert_success(self.run_generator())
        self.assert_success(self.run_generator("--check"))

    def test_invalid_markers_fail_without_writing_either_output(self):
        original = self.app.read_text(encoding="utf-8")
        for broken in (
            original.replace(BEGIN, ""),
            original.replace(END, ""),
            END + "\n" + BEGIN,
            original + "\n" + BEGIN,
            original + "\n" + END,
        ):
            for args in ((), ("--check",)):
                with self.subTest(content=broken[:80], args=args):
                    self.app.write_text(broken, encoding="utf-8")
                    before = self.snapshot()
                    result = self.run_generator(*args)
                    self.assertEqual(result.returncode, 1)
                    self.assertIn("config markers", result.stderr)
                    self.assertNotIn("Traceback", result.stderr)
                    self.assertEqual(self.snapshot(), before)


if __name__ == "__main__":
    unittest.main()
